import { Router } from "express";
import { requireAuth } from "../../middleware/require-auth";
import { requireRole } from "../../middleware/require-role";
import { requireCompleteRiderProfile } from "../../middleware/require-rider-profile";
import * as controller from "./assignment.controller";
import * as management from "../riders/management/rider-management.controller";

export const operatorAssignmentRouter = Router();
operatorAssignmentRouter.use((_req, res, next) => { res.setHeader("Cache-Control", "no-store"); next(); });
operatorAssignmentRouter.get("/riders", requireAuth, requireRole("OPERATOR"), management.list);
operatorAssignmentRouter.get("/riders/overview", requireAuth, requireRole("OPERATOR"), management.overview);
operatorAssignmentRouter.get("/riders/invitations", requireAuth, requireRole("OPERATOR"), management.invitations);
operatorAssignmentRouter.get("/riders/:riderId", requireAuth, requireRole("OPERATOR"), management.detail);
operatorAssignmentRouter.patch("/riders/:riderId", requireAuth, requireRole("OPERATOR"), management.update);
operatorAssignmentRouter.patch("/riders/:riderId/deactivate", requireAuth, requireRole("OPERATOR"), management.deactivate);
operatorAssignmentRouter.patch("/riders/:riderId/reactivate", requireAuth, requireRole("OPERATOR"), management.reactivate);
operatorAssignmentRouter.get("/assignments", requireAuth, requireRole("OPERATOR"), controller.operatorList);
operatorAssignmentRouter.post("/assignments", requireAuth, requireRole("OPERATOR"), controller.create);
export const riderDeliveryRouter = Router();
riderDeliveryRouter.use((_req, res, next) => { res.setHeader("Cache-Control", "no-store"); next(); });
riderDeliveryRouter.post("/parcel-scans/verify", requireAuth, requireRole("RIDER"), requireCompleteRiderProfile, controller.verifyParcelScan);
riderDeliveryRouter.get("/assignments", requireAuth, requireRole("RIDER"), requireCompleteRiderProfile, controller.riderList);
riderDeliveryRouter.get("/assignments/:id", requireAuth, requireRole("RIDER"), requireCompleteRiderProfile, controller.riderDetail);
riderDeliveryRouter.patch("/assignments/:id/status", requireAuth, requireRole("RIDER"), requireCompleteRiderProfile, controller.updateStatus);
